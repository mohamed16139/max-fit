"""Generate sw.js (the offline service worker) with the current list of app files and photos.

Run after changing any app file:   python3 scripts/build_sw.py
Check it's up to date (used by scripts/test.sh):   python3 scripts/build_sw.py --check

The version is a hash of every app file, so any change produces a new service worker and phones
pick up the update on their next online visit.
"""
import glob, hashlib, json, os, sys

APP = ["index.html", "manifest.webmanifest", "icon-192.png", "icon-512.png", "apple-touch-icon.png"] \
    + sorted(glob.glob("css/*.css")) + sorted(glob.glob("fonts/*.woff2")) + sorted(glob.glob("js/**/*.js", recursive=True))
IMAGES = sorted(glob.glob("img/ex/*.jpg"))

TEMPLATE = r'''// GENERATED by scripts/build_sw.py — do not edit by hand.
// Offline support: the whole app is saved on the first visit; exercise photos are saved as they're
// viewed and can be downloaded all at once in the background. Your data lives in localStorage, so it
// is always available offline.
const VERSION = "__VERSION__";
const APP_CACHE = "mf-app-" + VERSION, IMG_CACHE = "mf-img-v1";
const APP_FILES = __APP__;
const IMAGES = __IMAGES__;
const TIMEOUT = 3500;   // on a slow connection, fall back to the saved copy after this long

self.addEventListener("install", e => {
  e.waitUntil(caches.open(APP_CACHE).then(c => c.addAll(APP_FILES.map(u => new Request(u, {cache: "reload"})))).then(() => self.skipWaiting()));
});
self.addEventListener("activate", e => {
  e.waitUntil(caches.keys().then(ks => Promise.all(ks.filter(k => k.startsWith("mf-app-") && k !== APP_CACHE || k.startsWith("manga-fit-")).map(k => caches.delete(k))))
    .then(() => self.clients.claim()));
});

function withTimeout(p, ms) { return new Promise((res, rej) => { const t = setTimeout(() => rej(new Error("timeout")), ms); p.then(v => { clearTimeout(t); res(v); }, err => { clearTimeout(t); rej(err); }); }); }
// Network first (so updates arrive), saved copy when offline or slow.
async function networkFirst(req, key) {
  const cache = await caches.open(APP_CACHE);
  try {
    const res = await withTimeout(fetch(req), TIMEOUT);
    if (res.ok) cache.put(key || req, res.clone());
    return res;
  } catch (err) {
    return (await cache.match(key || req, {ignoreSearch: true})) || (await caches.match(key || req, {ignoreSearch: true})) || Response.error();
  }
}
// Photos never change: saved copy first.
async function cacheFirst(req) {
  const cache = await caches.open(IMG_CACHE), hit = await cache.match(req, {ignoreSearch: true});
  if (hit) return hit;
  const res = await fetch(req);
  if (res.ok) cache.put(req, res.clone());
  return res;
}
self.addEventListener("fetch", e => {
  const url = new URL(e.request.url);
  if (e.request.method !== "GET" || url.origin !== location.origin) return;
  if (e.request.mode === "navigate") return e.respondWith(networkFirst(e.request, "/index.html"));
  if (url.pathname.startsWith("/img/ex/")) return e.respondWith(cacheFirst(e.request));
  e.respondWith(networkFirst(e.request));
});

// ---------- download every photo in the background ----------
async function photoStatus() {
  const cache = await caches.open(IMG_CACHE), have = new Set((await cache.keys()).map(r => new URL(r.url).pathname));
  return {done: IMAGES.filter(u => have.has(u)).length, total: IMAGES.length, missing: IMAGES.filter(u => !have.has(u))};
}
async function broadcast(msg) { for (const c of await self.clients.matchAll()) c.postMessage(msg); }
let downloading = null;
function downloadPhotos() {
  if (downloading) return downloading;
  downloading = (async () => {
    const cache = await caches.open(IMG_CACHE);
    let {done, total, missing} = await photoStatus();
    for (let i = 0; i < missing.length; i += 6) {
      await Promise.all(missing.slice(i, i + 6).map(async u => {
        try { const r = await fetch(u); if (r.ok) { await cache.put(u, r); done++; } } catch (err) { /* offline: try again next time */ }
      }));
      broadcast({type: "photos", done, total});
    }
    broadcast({type: "photos", done, total, finished: true});
  })().finally(() => { downloading = null; });
  return downloading;
}
self.addEventListener("message", e => {
  const m = e.data || {};
  if (m.type === "download-photos") e.waitUntil(downloadPhotos());
  if (m.type === "status") e.waitUntil(photoStatus().then(s => e.source && e.source.postMessage({type: "status", version: VERSION, appFiles: APP_FILES.length, done: s.done, total: s.total})));
});
'''

def build():
    h = hashlib.sha256()
    for f in APP:
        h.update(f.encode()); h.update(open(f, "rb").read())
    h.update(json.dumps(IMAGES).encode())
    files = ["/"] + ["/" + f for f in APP]   # "/" and "/index.html" both cached so either URL opens offline
    return (TEMPLATE.replace("__VERSION__", h.hexdigest()[:12])
            .replace("__APP__", json.dumps(files))
            .replace("__IMAGES__", json.dumps(["/" + f for f in IMAGES])))

if __name__ == "__main__":
    os.chdir(os.path.join(os.path.dirname(__file__), ".."))
    out = build()
    if "--check" in sys.argv:
        cur = open("sw.js").read() if os.path.exists("sw.js") else ""
        if cur != out: print("sw.js is out of date: run python3 scripts/build_sw.py"); sys.exit(1)
        print("sw.js is up to date"); sys.exit(0)
    open("sw.js", "w").write(out)
    print(f"sw.js: {len(APP)} app files, {len(IMAGES)} photos")
